/**
 * Zod schema request body validator middleware
 * @param {import('zod').ZodSchema} schema
 */
export const validateBody = (schema) => {
  return async (req, res, next) => {
    try {
      req.body = await schema.parseAsync(req.body);
      next();
    } catch (error) {
      next(error);
    }
  };
};

