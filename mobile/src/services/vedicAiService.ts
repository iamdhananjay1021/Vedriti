/**
 * Async Vedic AI Query Processor (Checks backend server first, falls back to local knowledge)
 */
export interface DevoteeContext {
  name?: string;
  gotra?: string;
  rashi?: string;
  nakshatra?: string;
  city?: string;
}

export async function queryVedicAiAsync(
  userQuery: string,
  sessionId?: string,
  devoteeContext?: DevoteeContext
): Promise<VedicAiResponse & { sessionId?: string }> {
  try {
    const controller = new AbortController();
    const timeoutId = setTimeout(() => controller.abort(), 4000);

    const res = await fetch(`${SERVER_BASE_URL}/api/v1/ai/ask`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        query: userQuery,
        sessionId,
        devoteeContext,
      }),
      signal: controller.signal,
    });

    clearTimeout(timeoutId);

    if (res.ok) {
      const data = await res.json();
      if (data?.data?.answer) {
        return {
          answer: data.data.answer,
          sanskritVerse: data.data.sanskritVerse || data.data.sanskritShloka,
          shastraReference: data.data.shastraCitation || data.data.shastraReference,
          remedy: data.data.remedy,
          suggestedAction: data.data.action || (data.data.recommendedPujaSlug
            ? {
                type: 'puja',
                title: data.data.recommendedPujaName || 'Book Vedic Ritual',
                targetId: data.data.recommendedPujaSlug,
              }
            : undefined),
          followUpQuestions: data.data.followUps || [
            'आज का अभिजीत मुहूर्त क्या है?',
            'धनतेरस और दीपावली कब है?',
            'कुंडली में कालसर्प या मांगलिक दोष कैसे देखें?',
          ],
          sessionId: data.sessionId,
        };
      }
    }
  } catch (err) {
    // Network error or timeout, safely fall back to local knowledge
  }

  const local = queryVedicAi(userQuery);
  return { ...local, sessionId };
}
